// prop: pStream 的属性
// datas: 描述了音频源自己的属性
// 注意：二者的通道数可能不一致
template <typename TSample>
static bool MixAudioSamples(TSample* pStream, int len, std::vector<SAudioPlayData>& datas, const SAudioPlayerProp &prop)
{
	//auto tB = QueryHighTickCountUS();

	if (!pStream || datas.empty() || len <= 0 || prop.channels == 0 || prop.channels > CHANNEL_SYSTEM_MAX)
		return false;

	int samples = len / sizeof(TSample) / prop.channels;
	int *pDstSamples = new int[prop.channels * samples];
	memset(pDstSamples, 0, sizeof(int) * prop.channels * samples);
	for (std::size_t i = 0; i < datas.size(); i++) // mix all sources
	{
		MapChannelSamples(pDstSamples, prop.channels, (TSample*)datas[i].pAudioData, datas[i].ChannelMap, int(datas[i].fVolume * kAudioMixMaxVolume), samples);
	}

	const int max_audioval = ((1 << (sizeof(TSample) * 8 - 1)) - 1);
	const int min_audioval = -(1 << (sizeof(TSample) * 8 - 1));
	for (int *pBegin = pDstSamples, *pEnd = pDstSamples + prop.channels * samples; pBegin < pEnd;)
	{
		if (*pBegin > max_audioval)
		{
			*pBegin = max_audioval;
		}
		else if (*pBegin < min_audioval)
		{
			*pBegin = min_audioval;
		}
		*pStream++ = *pBegin++;
	}

	delete[] pDstSamples;

	//TRACE("MixAudio ########### %d: %lld\n", len, QueryHighTickCountUS() - tB);
	return true;
}

bool MixAudio(BYTE* stream, int len, std::vector<SAudioPlayData>& datas, const SAudioPlayerProp &prop)
{
	switch (prop.bitsPerSample)
	{
	case 8:
		return MixAudioSamples<INT8>((INT8*)stream, len, datas, prop);
	case 16:
		return MixAudioSamples<INT16>((INT16*)stream, len, datas, prop);
	default:
		assert(!"不支持的样本大小");
		return false;
	}
}
